// ============================================
// HDLBits: 7458 （复现一颗真实芯片的门电路）
// ============================================
//
// 【题目说明】
//   7458 芯片内含 4 个 AND 门 + 2 个 OR 门，是【两个互不相连】的独立电路：
//
//   第一路 p1y：两个 3 输入 AND，结果 OR
//     {p1a,p1b,p1c} → AND ┐
//                         ├─ OR → p1y
//     {p1d,p1e,p1f} → AND ┘
//
//   第二路 p2y：两个 2 输入 AND，结果 OR
//     {p2a,p2b} → AND ┐
//                     ├─ OR → p2y
//     {p2c,p2d} → AND ┘
//
// 【核心概念】
//   1. 多输入门：多个信号相与就把 & 串起来（a & b & c）；OR 同理串 |。
//   2. 一个模块可同时描述多个【独立】输出：各写一条 assign 即可。
//   3. 同一个 AND 门内，输入的书写顺序无所谓（与运算可交换），
//      关键是【分组】对——哪几根线进同一个门。
//
// 【易错点】
//   1. 读图时分组别搞错：务必顺着连线确认哪几个输入进同一个 AND 门。
//      这是本题唯一的真难点。
//   2. 每个 AND 组用括号括起来，让优先级清晰、无歧义。
//   3. 两个输出都要接，别漏掉 p2y。
//   4. 模块头是"一行声明多个 + input/output 交错"的密集写法，
//      题目已给好，照填中间逻辑即可，别被排版吓到。
// ============================================

module top_module ( 
    input p1a, p1b, p1c, p1d, p1e, p1f,
    output p1y,
    input p2a, p2b, p2c, p2d,
    output p2y );

    // 第一路：两个 3 输入 AND，再 OR
    assign p1y = (p1a & p1b & p1c) | (p1d & p1e & p1f);

    // 第二路：两个 2 输入 AND，再 OR
    assign p2y = (p2a & p2b) | (p2c & p2d);

endmodule