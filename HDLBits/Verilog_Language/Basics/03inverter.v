// ============================================
// HDLBits: notgate （非门 / 反相器）
// ============================================
//
// 【题目说明】
//   造一个 NOT 门：输出 out 是输入 in 的相反值。
//   in=0 -> out=1 ；in=1 -> out=0
//
//   真值表：
//     in │ out
//    ────┼────
//      0 │  1
//      1 │  0
//
// 【核心概念】
//   ~ 是"按位取反"运算符，语义上等于在导线中间放一个反相器。
//   assign 描述的是一根【永久存在】的连接，不是"执行一次"的语句：
//   in 一变，out 立刻跟着变。这是硬件思维，不是软件思维。
//
// 【易错点】
//   1. ~ vs !：
//      ~ = 按位取反（本题该用这个，语义是"接反相器"）
//      ! = 逻辑取反（判断整体真假）
//      对 1-bit 信号两者结果碰巧相同，但多位信号会完全不同，
//      所以从一开始就用 ~ 养成正确习惯。
//   2. 方向别写反：out（被驱动）在左，in（信号源）在右。
// ============================================

module top_module( input in, output out );

    assign out = ~in;   // 把 in 取反后接到 out：中间穿过一个反相器

endmodule