// ============================================
// HDLBits: xnorgate （同或门 / 异或非门）
// ============================================
//
// 【题目说明】
//   XNOR = NOT + XOR：先做 XOR(异或)，再整体取反。
//   含义 = "相等检测器"：两输入相同输出 1，不同输出 0。
//   口诀："相同为 1，不同为 0"。
//
//   真值表：
//     a  b │ XOR │ XNOR
//    ──────┼─────┼─────
//     0  0 │  0  │  1    ← 相同
//     0  1 │  1  │  0    ← 不同
//     1  0 │  1  │  0    ← 不同
//     1  1 │  0  │  1    ← 相同
//
//   硬件：一个 XOR 门，输出端加取反泡(○)，就成了 XNOR。
//
// 【核心概念】
//   ^ 是"按位异或"(不同为1,相同为0)。
//   XNOR 有两种等价写法：
//     写法一： ~(a ^ b)   —— 异或后整体取反（本题所用）
//     写法二： a ~^ b  或  a ^~ b   —— XNOR 专用符号，无需括号
//
// 【易错点】
//   1. 用写法一时括号必须有：~(a ^ b)。
//      写成 ~a ^ b 会变成 (~a) ^ b，是不同电路（~ 优先级高于 ^）。
//   2. ^ (异或/XOR) 与 ~^、^~ (同或/XNOR) 别混。
//      XNOR 专用符号只能是 ^~ 或 ~^，不要写成 ~& / ~|。
//   3. 口诀别记反：XOR 不同为1；XNOR 相同为1。本题是 XNOR。
// ============================================

module top_module( 
    input a, 
    input b, 
    output out );

    assign out = ~(a ^ b);   // 异或后整体取反 = XNOR = "相等检测器"

endmodule