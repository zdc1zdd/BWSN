// ===== HDLBits: Wire4 =====
// 题目:3 输入 (a,b,c) → 4 输出 (w,x,y,z),按指定方式连线
// 连接关系:a→w, b→x, b→y, c→z

module top_module( 
    input a,b,c,
    output w,x,y,z );

    assign w = a;   // a 驱动 w
    assign x = b;   // b 驱动 x —— b 同时接到 x 和 y
    assign y = b;   // b 再驱动 y  ← 这就是"扇出 fan-out":一根输入分出去接多个输出(合法)
    assign z = c;   // c 驱动 z

    // ---- 本节两个重点 ----
    // 1. 扇出(fan-out):一个输入可以驱动多个输出。合法。
    //    对比:一个输出被两个源驱动 = 冲突,禁止。方向反过来,合法性也反过来。
    //
    // 2. 多条 assign 之间没有先后顺序。
    //    这四根线是"同时存在"的物理导线,不是按行从上往下执行的代码。
    //    把这四行打乱顺序写,综合出来的电路完全一样。
    //    → 核心心态:不是在写顺序执行的程序,是在描述一堆同时通电的连线。

endmodule