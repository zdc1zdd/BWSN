// ============================================
// HDLBits: norgate （或非门）
// ============================================
//
// 【题目说明】
//   NOR = NOT + OR：先做 OR，再把结果整体取反。
//   口诀："全 0 才 1，有 1 就 0"（正好是 OR 的相反）。
//
//   真值表：
//     a  b │ OR │ NOR
//    ──────┼────┼────
//     0  0 │  0 │  1   ← 只有这一行是 1
//     0  1 │  1 │  0
//     1  0 │  1 │  0
//     1  1 │  1 │  0
//
//   硬件：一个 OR 门，在输出端加一个取反泡(○)，就成了 NOR。
//
// 【核心概念】
//   | 是"按位或"运算符（有 1 就 1，全 0 才 0）。
//   ~ 是"按位取反"。NOR = 对 OR 结果取反 = ~(a | b)。
//
// 【易错点】★本节最关键★
//   1. 括号不能少！必须写 ~(a | b)，让取反作用在【整个 OR 结果】上。
//      若写成 ~a | b，因为 ~ 优先级高于 |，会变成 (~a) | b，
//      即"先只反 a 再 OR"，是完全不同的电路，真值表对不上。
//      记牢：NOR 是"OR 完再一起反"，不是"反了某一个再 OR"。
//   2. | vs ||：本题用按位 |。1-bit 结果相同，但坚持用 | 养成习惯。
//   3. 内层是 OR(|) 不是 AND(&)，别和上一节 andgate 混。
// ============================================

module top_module( 
    input a, 
    input b, 
    output out );

    assign out = ~(a | b);   // 先 OR 再整体取反：这就是 NOR

endmodule