// =============================================================
// HDLBits - Vectors / Gates4  (Four-input gates)
// -------------------------------------------------------------
// 题目：
//   4 位输入 in[3:0]，三个 1 位输出：
//     out_and  = 4 输入与门
//     out_or   = 4 输入或门
//     out_xor  = 4 输入异或门
//
//   注意位宽的【形状】：4 位进，各 1 位出。
//
// -------------------------------------------------------------
// 核心概念：缩减运算符 (Reduction operators)
//
//   把 & | ^ 写成【一元】形式（只有一个操作数，符号写在前面），
//   就是缩减运算符 —— 把 N 位缩成 1 位：
//
//       &in  ≡  in[3] & in[2] & in[1] & in[0]    "全部都是 1 吗？"
//       |in  ≡  in[3] | in[2] | in[1] | in[0]    "有没有 1？"
//       ^in  ≡  in[3] ^ in[2] ^ in[1] ^ in[0]    奇偶校验
//
//   无论 in 多宽，缩减结果永远是 1 位。
//
//   【一元 vs 二元：同一个符号，两种身份】
//   判断依据只有一个：符号左边有没有操作数。
//
//       a & b   二元：按位与，两向量逐位配对，N 位进 N 位出
//       &a      一元：缩减与，一个向量内部全与起来，N 位进 1 位出
//
//   和数学里的减号一样：5 - 3 是二元减法，-3 是一元取负。
//
//   【两种方向的对比】
//   Vectorgates 的 a|b (横向逐位)        Gates4 的 &in (纵向汇总)
//
//     a[2]─┐                              in[3] ─┐
//          ├OR─out[2]                     in[2] ─┤
//     b[2]─┘                                     ├AND── out_and
//     a[1]─┐                              in[1] ─┤
//          ├OR─out[1]                     in[0] ─┘
//     b[1]─┘
//     a[0]─┐                              4 根线汇入同一个门
//          ├OR─out[0]
//     b[0]─┘
//     并排 3 个独立的门
//
//   【^in 是奇偶校验器，单独记住】
//   异或的性质：结果为 1 当且仅当输入中 1 的个数是【奇数】。
//       4'b0000 → 0 (零个1,偶)    4'b0001 → 1 (一个1,奇)
//       4'b0011 → 0 (两个1,偶)    4'b0111 → 1 (三个1,奇)
//       4'b1111 → 0 (四个1,偶)
//   工程上叫 parity，是最简单的错误检测：发数据时附带一位 ^data，
//   收到后重算对比，可发现任何【单个】比特翻转。
//   内存 ECC、串口通信里到处是它。^in 本身就是一个完整的奇偶校验生成器。
//
// -------------------------------------------------------------
// 易错点：
//
// 1) 一元和二元写混
//        assign out_and = in & in;   // ❌ 二元，逐位与自己 = in 本身(4位)
//                                    //    再截断成 1 位赋给 out_and，静默出错
//        assign out_and = &in;       // ✅ 一元缩减
//
// 2) Verilog 没有 ^^
//    & 有对应的 &&，| 有对应的 ||，但异或【只有】位运算符 ^ 这一条路。
//
// 3) 用 && 写 out_and —— 能过测试，但描述是错的
//        assign out_and = in[3] && in[2] && in[1] && in[0];
//    每个操作数都是 1 位，结果碰巧相同，HDLBits 会判通过。
//    但你描述的是"三次非零判断的串联"而不是"一个与门"，是碰运气的对。
//    → 养成用 & | ^ 的默认习惯，不要依赖"反正结果一样"。
//
// 4) 手写展开 vs 缩减写法（本题真正的考点）
//        assign out_and = in[0] & in[1] & in[2] & in[3];  // 功能对，但退回旧工具
//        assign out_and = &in;                            // 本节想要的写法
//    两者综合出的电路完全相同，差别在：
//      · 可扩展性：in 改成 32 位时，&in 一字不改；
//        手写版要敲 32 项，漏一位或打错下标【不会报错】，只会静默生成错的门。
//      · 意图表达：&in 一眼看出"对整个向量做全 1 检测"；
//        手写版要数一遍下标才能确认没漏。
//
// 5) 分清 &in 和 |in
//        &in → "全部都是 1 吗？"  （全 1 检测器）
//        |in → "有没有 1？"       （非零检测器，等价于 in != 0）
//    顺带：Vectorgates 里的 a || b 其实就是 (|a) | (|b)。
//
// 6) 与其他运算符混用时加括号
//        assign y = &a | &b;      // 语法上正确（一元优先级更高），但难读
//        assign y = (&a) | (&b);  // ✅ 推荐：三个符号两种身份，别赌优先级
//
// 7) 还有取反版本的缩减运算符（本题用不上，认识即可）
//        ~&in  缩减与非 = ~(&in)
//        ~|in  缩减或非 = ~(|in)   ← 是"先或起来再整体取反"，
//                                     不是"先每位取反再或"
//        ~^in  缩减异或非 = 偶校验
//
// -------------------------------------------------------------
// 与前面的联系：
//   · and_7458 里只能手写 a & b & c，因为那些是独立的 1 位信号，
//     不构成向量，没法缩减。这题的 in 是向量，才轮到缩减运算符登场。
//   · Vectorgates 的 | 是横向逐位配对；本题的 |in 是纵向汇总成 1 位。
//     同一个符号，看它是二元还是一元。
// =============================================================

module top_module( 
    input  [3:0] in,
    output out_and,
    output out_or,
    output out_xor
);

    assign out_and = &in;    // 4 输入与门：in 全为 1 时输出 1
    assign out_or  = |in;    // 4 输入或门：in 任意一位为 1 时输出 1
    assign out_xor = ^in;    // 4 输入异或门：in 中 1 的个数为奇数时输出 1（奇偶校验）

endmodule