// =============================================================
// HDLBits - Vectors / Vector2  (Vector part select)
// -------------------------------------------------------------
// 题目：
//   32 位输入 in[31:0] 视为 4 个字节，把【字节顺序】整个颠倒后输出。
//   本题综合结果依旧没有任何逻辑门，只是 32 根导线换了接法。
//
//     in :  [31:24] [23:16] [15:8]  [7:0]
//            byte3   byte2   byte1   byte0
//              │       │       │       │
//              └───────┼───────┼───────┼────┐
//                      └───────┼───────┼──┐ │
//                              └────┐  │  │ │
//                                   v  v  v v
//     out:  [31:24] [23:16] [15:8]  [7:0]
//            byte0   byte1   byte2   byte3
//
//   这就是真实工程里的【大端 / 小端转换 (endianness swap)】，
//   网络字节序 <-> x86 主机字节序之间转换时常用。
//
// -------------------------------------------------------------
// 核心概念：赋值号【左边】也能用 part-select
//
//   前面几题 assign 左边永远是一个完整信号，这题第一次出现：
//       assign out[31:24] = in[7:0];
//   完全合法。含义仍是"永久的物理连接"，只是精确指定了
//   要接到 out 这束线的哪 8 根上。
//   out 的 32 根线不必一次接完，可以分 4 次、每次接一段。
//
// -------------------------------------------------------------
// 易错点：
//
// 1) 只搬字节，不动字节内部的位
//    in[7:0] 这 8 根线整体搬到 out[31:24] 后，
//    in[7] 仍是该字节最高位（→ out[31]），in[0] 仍是最低位（→ out[24]）。
//        in  = AA BB CC DD  →  out = DD CC BB AA   ✅
//        逐位倒过来                                 ❌ 那是后面 vectorr 的题
//
// 2) 必须把 32 根线全部驱动
//    在 assign 的世界里，没被驱动的线是 z（高阻/悬空），不是 0。
//    漏写一条 assign，那一段仿真波形就是 zzzz，直接判错。
//    → 写完数：4 条 assign × 8 位 = 32 位，正好覆盖满。
//
// 3) 同一根线不能被驱动两次
//        assign out[31:24] = in[7:0];
//        assign out[31:24] = in[15:8];   // ❌ 两个驱动源打架 → X
//    这是"硬件描述"与"写程序"最尖锐的分歧：
//        C  ：x = 1; x = 2;  → 结果是 2（后者覆盖前者）
//        HDL：两条 assign 同时永久生效 → 短路冲突，结果是 X
//
// 4) 范围必须降序
//    信号声明为 [31:0]，所有 part-select（左边和右边）都得写降序：
//        out[31:24] ✅        out[24:31] ❌
//
// 5) 左右位宽必须相等
//    out[31:24] 是 8 位，右边也必须给 8 位。
//    给 16 位会被静默截断，不报错。
//
// 6) `default_nettype none 与端口 wire 必须成套
//    Vector1 的模板带了该指令，所以端口写 input wire [15:0] in；
//    本题模板没带，所以端口写 input [31:0] in 即可。
//    若加了指令却不给端口补 wire → 编译报错。跟着模板走。
//
// -------------------------------------------------------------
// 与前面的联系：
//   assign 依旧是永久连接、多条之间无先后顺序、同时成立。
//   新增的只是"左边也能切片"这一条语法能力。
//
// 后续：
//   这题用拼接运算符 {} 一行就能写完（vector3 会教）：
//       assign out = {in[7:0], in[15:8], in[23:16], in[31:24]};
//   现在先用 4 条 assign 把 part-select 的手感练扎实。
// =============================================================

module top_module( 
    input  [31:0] in,
    output [31:0] out
);

    // 4 条 assign 同时存在、无先后顺序，行的次序可任意调换。
    // 每条搬运一个完整字节，字节内部的位序保持不变。

    assign out[31:24] = in[7:0];      // in 的 byte0 → out 的 byte3
    assign out[23:16] = in[15:8];     // in 的 byte1 → out 的 byte2
    assign out[15:8]  = in[23:16];    // in 的 byte2 → out 的 byte1
    assign out[7:0]   = in[31:24];    // in 的 byte3 → out 的 byte0

endmodule