// =============================================================
// HDLBits - Vectors / Vector1  (Vectors in more detail)
// -------------------------------------------------------------
// 题目：
//   把 16 位输入 in[15:0] 拆成高 8 位 out_hi 和低 8 位 out_lo。
//   本题综合结果里没有任何逻辑门，纯粹是导线的重新分组。
//
// -------------------------------------------------------------
// 核心概念 1：向量 / 总线 (packed vector)
//   wire [15:0] in;
//   不是"一个能存 16 位数的变量"，而是"捆成一束的 16 根物理导线"，
//   方括号是给这 16 根线编号。方括号写在【名字前面】= packed 维度。
//
// 核心概念 2：bit-select 与 part-select
//   in[15]     取出单根线        → 1 位
//   in[15:8]   取出连续一段      → 8 位
//   取出来的这一束会【从最右端(LSB)重新从 0 编号】：
//
//     in :  [15][14][13][12][11][10][ 9][ 8]  [ 7]...[ 0]
//             |   |   |   |   |   |   |   |
//             v   v   v   v   v   v   v   v
//     out_hi:[ 7][ 6][ 5][ 4][ 3][ 2][ 1][ 0]
//
//   所以 in[8] 接的是 out_hi[0]，不是 out_hi[8]。
//
// 核心概念 3：packed vs unpacked（现在只用 packed，认识即可）
//   wire [7:0] a;        // packed  ：1 个信号，8 位宽（一条总线）
//   wire       b [7:0];  // unpacked：8 个独立的 1 位信号（一份清单）
//   reg  [7:0] mem [255:0];  // 256 个 8 位单元 → 存储器
//   packed 能整体赋值、能切片、能做算术；unpacked 只能一次点名一个元素。
//
// -------------------------------------------------------------
// 易错点：
//
// 1) 隐式网络 (implicit net) —— 最阴险的坑
//    用了没声明过的信号名，Verilog 不报错，会自动造一根【1 位】线。
//        wire [2:0] a, c;
//        assign a = 3'b101;
//        assign b = a;   // b 未声明 → 自动 1 位 → 只接上 a[0]，b = 1
//        assign c = b;   // 1 位补零成 3 位 → c = 001，不是 101
//    全程零报错。打错一个字母就会静默接错电路。
//    → 文件开头写 `default_nettype none 关掉这个功能，让它变成编译错误。
//      注意开头是【反引号】，和 `timescale 一样是编译器指令，不是语句，
//      所以行尾没有分号。
//    → 代价：所有端口必须显式写 wire，如 input wire [15:0] in。
//
// 2) 位序不能中途翻转
//    in 声明为 [15:0]（降序），所有 part-select 也必须降序：
//        in[15:8]  ✅        in[8:15]  ❌ 报错
//    part-select 不能用来反转位序。
//
// 3) 位宽不匹配是【静默】的
//    宽 → 窄：直接截断高位；窄 → 宽：高位补零。多数工具只给 warning。
//        assign out_lo = in;   // 16 位塞进 8 位，高 8 位被丢弃，不报错
//    习惯：写完每条 assign，数一下等号两边位宽是否相等。
//
// 4) unpacked 别和 packed 写混（见核心概念 3）
//
// -------------------------------------------------------------
// 与前面的联系：
//   assign 的含义没有任何变化，依旧是"永久的物理连接"，
//   依旧是多条 assign 之间无先后顺序、同时成立。
//   变的只是被连接的对象：从 1 根线 → 一束线。
//
// 本地用 iverilog 时的提示：
//   `default_nettype none 的作用范围是从该行往后的整个编译过程，
//   会影响后续一起编译的其他文件。工程里的标准做法是在文件末尾
//   （endmodule 之后）用 `default_nettype wire 恢复默认。
//   单文件练习不加也没问题。
// =============================================================

`default_nettype none    // 禁用隐式网络：未声明的信号直接报错，而不是被偷偷造成 1 位线

module top_module(
    input  wire [15:0] in,       // 16 根输入导线，编号 15..0
    output wire [7:0]  out_hi,   // 8 根输出导线，编号 7..0
    output wire [7:0]  out_lo    // 8 根输出导线，编号 7..0
);

    // 两条 assign 是【同时存在】的两组连线，没有执行顺序，
    // 写的先后可以任意调换。

    assign out_lo = in[7:0];     // in[7]..in[0]   → out_lo[7]..out_lo[0]
    assign out_hi = in[15:8];    // in[15]..in[8]  → out_hi[7]..out_hi[0]
                                 //   ↑ 注意重新编号：in[8] 对应 out_hi[0]

endmodule