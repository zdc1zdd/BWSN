// =============================================================
// HDLBits - Vectors / Vector3  (Vector concatenation operator)
// -------------------------------------------------------------
// 题目：
//   六个 5 位输入 a b c d e f（共 30 位），四个 8 位输出 w x y z（共 32 位）。
//   把六个输入首尾相接排成一长串，末尾补两个 1 凑够 32 位，
//   再从最左边(MSB)开始每 8 位切一刀，依次给 w x y z。
//   依旧是零逻辑门的纯接线电路。
//
//   位置: 31        24 23        16 15         8 7          0
//         ├─────w─────┤├─────x─────┤├─────y─────┤├─────z─────┤
//         ├──a──┼──b──┼┼─┼───c───┼─┼┼──d──┼──e──┼┼─┼───f───┼─┤
//                    ↑            ↑           ↑         ↑
//                b 被劈开     d 被劈开    e 被劈开   f 后接补位
//
//   注意：5 和 8 不整除，所以【切割边界和输入边界对不齐】，
//   一个输入常常横跨两个输出（b 的高 3 位在 w 里、低 2 位在 x 里）。
//   这正是拼接运算符存在的理由 —— 手算这些下标既费劲又极易出错。
//
// -------------------------------------------------------------
// 核心概念 1：拼接运算符 {}
//
//   { a, b, c }  把这些信号首尾相接，组成一个更宽的信号。
//     · 最左边是最高位(MSB)，最右边是最低位(LSB)
//     · 结果位宽 = 各部分位宽之和
//     · 逗号分隔，最外面一层大括号
//
//       wire [2:0] a = 3'b101;
//       wire [1:0] b = 2'b01;
//       {a, b}     // 5 位: 10101
//       {b, a}     // 5 位: 01101   顺序不同，结果不同
//       {a, 1'b0}  // 4 位: 1010
//
//   硬件上它什么都不做，只是给"这一束线该怎么排"起了个名字。
//
// 核心概念 2：{} 也能放在等号【左边】
//
//   Vector2 教过左边可以 part-select，这里更进一步：左边可以是一个拼接。
//       assign {w, x, y, z} = ...;
//   意思是"把这四束线临时看成一根 32 位大总线，整体接线"。
//   右边的 32 位会【自动按位宽依次落到】w(8) x(8) y(8) z(8) 上，
//   完全不用管切割边界在哪。整题因此只需一行。
//
// -------------------------------------------------------------
// 易错点：
//
// 1) {} 里不能用无位宽字面量 —— 本题最常见的编译错误
//        assign {w,x,y,z} = {a,b,c,d,e,f,1,1};        // ❌ 编译错误
//        assign {w,x,y,z} = {a,b,c,d,e,f,2'b11};      // ✅
//        assign {w,x,y,z} = {a,b,c,d,e,f,1'b1,1'b1};  // ✅ 也对
//    裸写的 1 是无位宽字面量(unsized literal)，Verilog 默认按 32 位处理，
//    编译器无法确定它在拼接里该贡献几位 → 语言标准直接禁止。
//
//    规则：{} 里每一项都必须有明确位宽。信号天然有；常量必须写成 位宽'进制值：
//        2'b11   2 位二进制 11
//        1'b0    1 位 0
//        8'hFF   8 位十六进制 FF
//        4'd9    4 位十进制 9
//
// 2) 两边位宽总数没对齐 —— 静默出错
//        左边 8+8+8+8 = 32
//        右边 5×6 + 2 = 32   ✅
//    补成 3'b111 (33位) 或忘了补位 (30位) 都【不报错】，
//    只会截断或补零，波形大面积错。
//    → 写完必须数一遍两边位宽总和。（"位宽不匹配是静默的"第三次出现）
//
// 3) 顺序写反
//    a 在最左 = 最高位 → 落到 w 里；
//    两个补位 1 在最右 = 最低位 → 落到 z[1:0]。
//    题目说"序列【后面】跟两个 1"，所以补位在右边，不在左边。
//
// 4) {} 的第二种用法：复制运算符，别混淆
//        { a, b }     拼接：a 接上 b
//        { 3{a} }     复制：a 重复 3 次，等价于 {a,a,a}
//        { 3{1'b1} }  等价于 3'b111
//    区别在于大括号内部【开头有没有一个数字】。
//    本题补位也可写成 {2{1'b1}}，但直接写 2'b11 更清楚。
//    复制运算符在 vector4（符号扩展）会真正用上。
//
// 5) {} 不能用来反转位序
//    它只能重排"块"，不能自动把一个向量内部的位倒过来。
//    想反转得逐位拼：{a[0],a[1],a[2]}。那是后面 vectorr 的内容。
//
// -------------------------------------------------------------
// 语法小记：一次声明多个同宽信号
//        input [4:0] a, b, c, d, e, f;
//    位宽 [4:0] 对逗号后面【每一个】都生效，等价于分别写六行。
//
// -------------------------------------------------------------
// 与前面的联系：
//   · Vector2：左边可以 part-select → 本题：左边可以是拼接。
//     两者都是"精确指定要接到输出总线的哪些线上"。
//   · 若不用 {}，本题得手算切割点写四行，且每行内部仍然离不开 {}：
//         assign w = { a, b[4:2] };
//         assign x = { b[1:0], c, d[4] };
//         assign y = { d[3:0], e[4:1] };
//         assign z = { e[0], f, 2'b11 };
//     可以对照着看，体会一行 vs 四行的差别。
// =============================================================

module top_module (
    input  [4:0] a, b, c, d, e, f,
    output [7:0] w, x, y, z
);

    // 左边 32 位，右边 32 位，位宽自动对齐，无需关心切割边界。
    assign {w, x, y, z} = {a, b, c, d, e, f, 2'b11};

endmodule