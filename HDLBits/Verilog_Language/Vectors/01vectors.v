// ============================================
// HDLBits: vector0 （第一次接触向量 / 一捆线）
// ============================================
//
// 【题目说明】
//   输入 vec 是一捆 3 根线(3-bit)。要做两件事：
//   1. 把整捆 vec 原样输出到 3-bit 的 outv；
//   2. 把这捆线拆开，第 2/1/0 根分别接到单线 o2/o1/o0。
//
//         vec[2] vec[1] vec[0]
//    vec ══╪══════╪══════╪══   ← 一捆 3 根线(总线/bus)
//          ├──────┼──────┼──→ outv  (整捆原样,还是 3 根)
//          ↓      ↓      ↓
//          o2     o1     o0    ← 从捆里各抽一根,变单线
//
// 【核心概念】
//   1. [2:0] = 声明一捆 3 根线，给它们编号 2,1,0。
//      约定：左边大数(2)=最高位 MSB，右边小数(0)=最低位 LSB。
//      坚持写 [高:低] 这个标准顺序，别写成 [0:2]。
//   2. vec[n] = 用下标从捆里【抽出第 n 根单线】。
//      方括号+一个数字 = 选中总线里的某一根。
//   3. 向量不是新机制，就是"把多根 wire 打包"的简写：
//      assign outv = vec;  等价于 0接0、1接1、2接2 三条并排的连接。
//   4. 多条 assign 无先后顺序：o0/o1/o2 三条谁先写都一样(同时成立)。
//
// 【易错点】
//   1. ★编号别接反★：o0=vec[0]、o1=vec[1]、o2=vec[2]。
//      别把 o0 手滑接到 vec[2](最高位)上。
//   2. 位宽要匹配：3 位的 vec 不能直接接到 1 位的 o0，
//      取单根必须用下标 vec[0]。
//   3. 四个输出(outv/o2/o1/o0)都要接，别漏。
// ============================================

module top_module ( 
    input wire [2:0] vec,
    output wire [2:0] outv,
    output wire o2,
    output wire o1,
    output wire o0  );

    assign outv = vec;      // 整捆原样接过去(两边都是3位,可省略 [2:0])
    assign o2 = vec[2];     // 抽第 2 根(MSB)
    assign o1 = vec[1];     // 抽第 1 根
    assign o0 = vec[0];     // 抽第 0 根(LSB)

endmodule