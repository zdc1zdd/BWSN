// =============================================================
// HDLBits - Vectors / Vectorgates  (Bitwise operators)
// -------------------------------------------------------------
// 题目：
//   两个 3 位输入 a[2:0]、b[2:0]，产生三个输出：
//     out_or_bitwise[2:0]  按位或
//     out_or_logical       逻辑或（1 位！）
//     out_not[5:0]         高半 [5:3] = ~b，低半 [2:0] = ~a
//
//   这是第一道真正长出【门电路】的向量题。
//   Vector1 / Vector2 只是接线，这题会综合出反相器和或门。
//
// -------------------------------------------------------------
// 核心概念：按位运算符 vs 逻辑运算符，在向量上本质不同
//
//   前面 norgate / xnorgate 里信号都是 1 位，两种写法碰巧结果一样，
//   所以感受不到差别。信号一变宽，差别就是本质性的。
//
//   【按位或 |】逐位配对，各算各的，3 个独立的 2 输入或门：
//
//       a[2] ─┐          a[1] ─┐          a[0] ─┐
//             ├OR─out[2]       ├OR─out[1]       ├OR─out[0]
//       b[2] ─┘          b[1] ─┘          b[0] ─┘
//
//       输入 3 位 → 输出 3 位
//
//   【逻辑或 ||】先把整个向量压成一个"真假"，再或。
//   它问的是"a 这个数非零吗？"和"b 这个数非零吗？"
//   等价于把 6 根线全塞进一个大或门：任何一位是 1，输出就是 1。
//
//       a[2]─┐
//       a[1]─┼OR─┐   "a 非零?"
//       a[0]─┘   ├OR── out_or_logical  (1 位)
//       b[2]─┐   │
//       b[1]─┼OR─┘   "b 非零?"
//       b[0]─┘
//
//       输入 3+3 位 → 输出只有 1 位
//
//   具体数字对比：
//       a = 3'b100, b = 3'b011  →  a|b = 3'b111 , a||b = 1'b1
//       a = 3'b100, b = 3'b000  →  a|b = 3'b100 , a||b = 1'b1  ← 与上组相同
//   可见 || 丢掉了大量信息：只能回答"有没有 1"，不能说出 1 在哪。
//
//   取反同理：
//       ~a  → 3 个反相器，输出 3 位     ~3'b100 = 3'b011
//       !a  → "a 是零吗？"，输出 1 位    !3'b100 = 1'b0
//
//   结论：硬件描述里 ~ & | ^ 是默认选择；! && || 只在确实需要
//   "这个数是否非零"这类判断时才用。本题刻意各考一次。
//
// -------------------------------------------------------------
// 易错点：
//
// 1) 把按位结果赋给 1 位输出 —— 静默出错
//        assign out_or_logical = a | b;   // ❌
//    右 3 位、左 1 位 → 截断，实际只得到 a[0] | b[0]，且不报错。
//
// 2) out_not 是 6 位，不能整体赋 3 位的值
//        assign out_not = ~a;   // ❌
//    右 3 位、左 6 位 → 高位补零，out_not[5:3] 全 0 而非 ~b，且不报错。
//    正确做法：用 Vector2 学的【左边 part-select】分两段接。
//
// 3) a 和 b 的上下半容易放反
//    题目要求 ~b 在【上】(5:3)、~a 在【下】(2:0)，
//    与端口顺序(a 在前)相反，读题时要圈一下。
//
// 4) 别把 | 和 || 当成"一个意思的两种写法"
//    它们描述的是两套完全不同的硬件：
//    3 个 2 输入或门  vs  1 个 6 输入大或门。
//
// 5) out_or_logical 的端口没有方括号 = 1 位，不要自行加宽。
//
// -------------------------------------------------------------
// 与前面的联系：
//   · assign 仍是永久连接，多条之间无先后顺序。
//   · out_not 用到 Vector2 的"左边可以切片"，两段拼满 6 位、
//     不重不漏（漏了会悬空成 z，重了会驱动冲突成 X）。
//   · "位宽不匹配是静默的"（Vector1 易错点 3）在这题第一次真正咬人。
//
// 前瞻：
//   Verilog 还有【缩减运算符】——一元的 |a 表示"把 a 的所有位或起来"，
//   结果 1 位。所以 (|a) | (|b) 与本题的 a || b 效果相同。
//   属于后面 More Verilog Features 的内容，现在知道有这回事即可。
// =============================================================

module top_module( 
    input  [2:0] a,
    input  [2:0] b,
    output [2:0] out_or_bitwise,
    output       out_or_logical,
    output [5:0] out_not
);

    assign out_or_bitwise = a | b;    // 3 位 = 3 位，逐位配对
    assign out_or_logical = a || b;   // 1 位 = 1 位，"a 非零 或 b 非零"

    assign out_not[2:0] = ~a;         // 低半：a 逐位取反
    assign out_not[5:3] = ~b;         // 高半：b 逐位取反（注意是 b 不是 a）

endmodule
